<script>
    function parseDmyDate(dateStr) {
        if (!dateStr) return null;
        var parts = dateStr.trim().split("/");
        if (parts.length !== 3) return null;
        var day = parseInt(parts[0], 10);
        var month = parseInt(parts[1], 10) - 1;
        var year = parseInt(parts[2], 10);
        return new Date(year, month, day);
    }

    document.addEventListener("DOMContentLoaded", function() {
        document.querySelectorAll(".js-searchable-select").forEach(function(selectEl) {
            if (!selectEl.dataset.choicesInitialized) {
                new Choices(selectEl, {
                    searchEnabled: true,
                    shouldSort: false,
                    removeItemButton: true,
                    placeholder: true,
                    placeholderValue: selectEl.options[0] ? selectEl.options[0].text : "Select Project...",
                    searchPlaceholderValue: "Ketik nama project untuk mencari...",
                    noResultsText: "Project tidak ditemukan",
                    noChoicesText: "Tidak ada project tersedia",
                    itemSelectText: "Tekan untuk pilih"
                });
                selectEl.dataset.choicesInitialized = "true";
            }
        });
    });

    $(document).on("click", "#button-search-data", function(e) {
        e.preventDefault();
        var project = document.getElementById("data_project").value;
        var tanggalAwal = document.getElementById("data_tanggal_awal").value;
        var tanggalAkhir = document.getElementById("data_tanggal_akhir").value;

        if (tanggalAwal === "" || tanggalAkhir === "") {
            Swal.fire({
                icon: "error",
                title: "Oops...",
                text: "Silakan pilih Tanggal Awal dan Tanggal Akhir terlebih dahulu!"
            });
            $('#menu-general-ledger').html('');
            return;
        }

        $('#menu-general-ledger').html(
            '<div class="py-5 text-center">' +
            '<div class="spinner-border text-primary mb-2" role="status"><span class="visually-hidden">Loading...</span></div>' +
            '<div class="small fw-semibold opacity-75">Memuat data General Ledger...</div>' +
            '</div>'
        );

        $.ajax({
            url: "{{ route('general_ledger_search') }}",
            type: "POST",
            cache: false,
            data: {
                "_token": "{{ csrf_token() }}",
                "project": project,
                "tanggal_awal": tanggalAwal,
                "tanggal_akhir": tanggalAkhir
            },
            dataType: 'html',
        }).done(function(data) {
            $('#menu-general-ledger').html(data);
        }).fail(function() {
            $('#menu-general-ledger').html(
                '<div class="p-4 text-center text-danger fw-bold">' +
                '<i class="fas fa-exclamation-triangle me-1"></i> Gagal memuat data General Ledger.' +
                '</div>'
            );
        });
    });
</script>
