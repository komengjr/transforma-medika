<script src="https://cdn.datatables.net/2.2.2/js/dataTables.js"></script>
<script src="https://cdn.datatables.net/2.2.2/js/dataTables.bootstrap5.js"></script>
<script src="https://cdn.datatables.net/responsive/3.0.4/js/dataTables.responsive.js"></script>
<script src="https://cdn.datatables.net/responsive/3.0.4/js/responsive.bootstrap5.js"></script>
<script src="{{ asset('vendors/choices/choices.min.js') }}"></script>
<script src="{{ asset('asset/js/flatpickr.js') }}"></script>
<script src="https://cdn.jsdelivr.net/npm/select2@4.1.0-rc.0/dist/js/select2.min.js"></script>

<script>
    let labTable;
    let activeLabHandlingAjax = null;

    function initSelect2Lab(selector) {
        if (!(window.jQuery && $.fn.select2)) return;
        $(selector).each(function() {
            const $el = $(this);
            if ($el.hasClass('select2-hidden-accessible')) {
                $el.select2('destroy');
            }
            const placeholderText = $el.data('placeholder') || $el.find('option:first').text() || 'Pilih';
            $el.select2({
                theme: 'bootstrap-5',
                width: '100%',
                placeholder: placeholderText,
                allowClear: true,
                language: {
                    noResults: function() {
                        return 'Data tidak ditemukan';
                    },
                    searching: function() {
                        return 'Mencari...';
                    }
                }
            });
        });
    }

    function extractRegCodeFromHtml(actionHtml) {
        if (!actionHtml) return '';
        const match = String(actionHtml).match(/data-code=["']([^"']+)["']/i);
        return match ? match[1] : '';
    }

    $(document).ready(function() {
        initSelect2Lab('.select2-filter-lab');

        loadFilterOptions();

        labTable = $('#example').DataTable({
            processing: true,
            serverSide: true,
            responsive: true,
            ajax: {
                url: "{{ route('data_registrasi_lab_table') }}",
                type: "POST",
                data: function(d) {
                    d._token = "{{ csrf_token() }}";
                    d.tgl1 = $('#filter_tgl_awal').val();
                    d.tgl2 = $('#filter_tgl_akhir').val();
                    d.search_custom = $('#filter_search').val();
                    d.dokter = $('#filter_dokter').val();
                    d.penjamin = $('#filter_penjamin').val();
                    d.pemeriksaan = $('#filter_pemeriksaan').val();
                }
            },
            columns: [{
                    data: 'action',
                    className: 'action-cell-full text-center align-middle',
                    orderable: false,
                    searchable: false,
                    render: function(data, type, row) {
                        const regCode = extractRegCodeFromHtml(data) || row.no_registrasi || row.id || '';
                        const safeCode = String(regCode).replace(/"/g, '&quot;');
                        return `<div class="dropdown">
                            <button class="btn" type="button" data-bs-toggle="dropdown" aria-expanded="false" title="Menu Aksi">
                                <i class="fas fa-ellipsis-v"></i>
                            </button>
                            <ul class="dropdown-menu ent-dropdown-menu py-2">
                                <li>
                                    <a class="dropdown-item fw-semibold py-2 button-proses-handling-lab" href="#" data-bs-toggle="modal" data-bs-target="#modal-lab" data-code="${safeCode}">
                                        <i class="fas fa-flask me-2 text-primary"></i> Proses Handling Lab
                                    </a>
                                </li>
                            </ul>
                        </div>`;
                    }
                },
                {
                    data: 'no',
                    className: 'text-center align-middle fw-semibold',
                    orderable: false,
                    searchable: false
                },
                {
                    data: 'no_registrasi',
                    className: 'align-middle',
                    orderable: false
                },
                {
                    data: 'nama_pasien',
                    className: 'align-middle',
                    orderable: false
                },
                {
                    data: 'tanggal_reg',
                    className: 'align-middle text-nowrap',
                    orderable: false
                },
                {
                    data: 'rujukan',
                    className: 'align-middle',
                    orderable: false
                },
                {
                    data: 'pemeriksaan',
                    className: 'align-middle',
                    orderable: false
                },
                {
                    data: 'status',
                    className: 'text-center align-middle',
                    orderable: false,
                    searchable: false
                }
            ],
            language: {
                search: "_INPUT_",
                searchPlaceholder: "Cari data...",
                lengthMenu: "Tampilkan _MENU_ data",
                info: "Menampilkan _START_ - _END_ dari _TOTAL_ data",
                paginate: {
                    first: "Awal",
                    last: "Akhir",
                    next: "<i class='fas fa-angle-right'></i>",
                    previous: "<i class='fas fa-angle-left'></i>"
                },
                processing: `
                    <div class="custom-loader py-3 text-center">
                        <div class="spinner-border text-primary mb-2" style="width: 2rem; height: 2rem;" role="status"></div>
                        <span class="fw-semibold small d-block">Memuat data laboratorium...</span>
                    </div>
                `
            },
            pageLength: 10
        });

        $('#filter_tgl_awal, #filter_tgl_akhir').on('change', function() {
            loadFilterOptions();
            labTable.ajax.reload(null, false);
        });

        $('#filter_dokter, #filter_penjamin, #filter_pemeriksaan').on('change', function() {
            labTable.ajax.reload(null, false);
        });

        $('#filter_search').on('keyup', function() {
            labTable.ajax.reload(null, false);
        });

        $('#btn-refresh-lab').on('click', function(e) {
            e.preventDefault();
            const today = new Date().toISOString().split('T')[0];
            $('#filter_tgl_awal').val(today);
            $('#filter_tgl_akhir').val(today);
            $('#filter_search').val('');
            $('#filter_dokter').val('').trigger('change.select2');
            $('#filter_penjamin').val('').trigger('change.select2');
            $('#filter_pemeriksaan').val('').trigger('change.select2');
            loadFilterOptions();
            labTable.ajax.reload(null, false);
        });

        const modalLabEl = document.getElementById('modal-lab');
        if (modalLabEl) {
            modalLabEl.addEventListener('hidden.bs.modal', function() {
                if (activeLabHandlingAjax && activeLabHandlingAjax.readyState !== 4) {
                    activeLabHandlingAjax.abort();
                    activeLabHandlingAjax = null;
                }
                $('#menu-lab').empty();
            });
        }
    });

    function loadFilterOptions() {
        const tglAwal = $('#filter_tgl_awal').val();
        const tglAkhir = $('#filter_tgl_akhir').val();

        fetch(`/pelayanan/get-filter-options?tgl1=${tglAwal}&tgl2=${tglAkhir}`)
            .then(res => res.json())
            .then(data => {
                if (data.success) {
                    const $dokter = $('#filter_dokter'),
                        selectedDokter = $dokter.val();
                    $dokter.empty().append('<option value="">Semua Dokter</option>');
                    (data.dokter || []).forEach(d => $dokter.append(new Option(d, d, false, d === selectedDokter)));
                    $dokter.trigger('change.select2');

                    const $penjamin = $('#filter_penjamin'),
                        selectedPenjamin = $penjamin.val();
                    $penjamin.empty().append('<option value="">Semua Kelompok</option>');
                    (data.penjamin || []).forEach(p => $penjamin.append(new Option(p, p, false, p === selectedPenjamin)));
                    $penjamin.trigger('change.select2');

                    const $pemeriksaan = $('#filter_pemeriksaan'),
                        selectedPemeriksaan = $pemeriksaan.val();
                    $pemeriksaan.empty().append('<option value="">Semua Pemeriksaan</option>');
                    (data.pemeriksaan || []).forEach(item => $pemeriksaan.append(new Option(item.nama_layanan, item.id, false, item.id == selectedPemeriksaan)));
                    $pemeriksaan.trigger('change.select2');
                }
            }).catch(err => console.error("Gagal memuat opsi filter:", err));
    }

    $(document).on("click", ".button-proses-handling-lab", function(e) {
        e.preventDefault();
        var code = $(this).data("code");

        if (activeLabHandlingAjax && activeLabHandlingAjax.readyState !== 4) {
            activeLabHandlingAjax.abort();
        }

        $('#menu-lab').html(`
            <div class="custom-loader py-5 text-center">
                <div class="spinner-border text-primary mb-2" role="status" style="width: 2.5rem; height: 2.5rem;"></div>
                <p class="mt-3 mb-0 fw-semibold small">Memuat data pemeriksaan...</p>
            </div>
        `);

        activeLabHandlingAjax = $.ajax({
            url: "{{ route('data_registrasi_lab_handling') }}",
            type: "POST",
            cache: false,
            data: {
                "_token": "{{ csrf_token() }}",
                "code": code
            },
            dataType: 'html',
        }).done(function(data) {
            $('#menu-lab').html(data);
        }).fail(function(xhr, status) {
            if (status === 'abort') return;
            $('#menu-lab').html('<div class="alert alert-danger m-4 rounded-3" role="alert"><i class="fas fa-exclamation-triangle me-2"></i>Gagal memuat data. Silakan coba lagi.</div>');
        }).always(function() {
            activeLabHandlingAjax = null;
        });
    });
</script>
@endsection
